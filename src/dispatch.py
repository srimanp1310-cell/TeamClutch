# gates
# ---------------------------------------------------------------------------

def _supported_dtypes(name: str, cls: Optional[type]) -> Optional[frozenset]:
    """Dtypes this strategy claims to be correct in, or None for "all".

    Only a class can declare this. A name appearing in the JSON table with no
    class behind it on this machine is already excluded by the registration
    gate, so there is nothing to guess.
    """
    declared = getattr(cls, "SUPPORTED_DTYPES", None)
    if declared is None:
        return None
    return frozenset(str(d).replace("torch.", "") for d in declared)


def _minimum_capability(name: str, cls: Optional[type]) -> Optional[Tuple[int, int]]:
    """What this strategy needs. A class declaration beats the name heuristic.

    The heuristic exists because dispatch has to be able to reason about a name
    that appears only in the JSON table, with no class behind it on this
    machine. A class that declares `MIN_CAPABILITY` is always believed instead —
    a strategy knows its own requirements better than its name does.
    """
    declared = getattr(cls, "MIN_CAPABILITY", None)
    if declared is not None:
        return tuple(declared)  # type: ignore[return-value]
    lowered = name.lower()
    needed = [
        requirement for marker, requirement in _NAME_CAPABILITY_RULES
        if marker in lowered
    ]
    return max(needed) if needed else None


#: (name, minimum capability or None, supported dtypes or None) for everything
#: runnable here. Resolved before memoisation so the cache key carries the
#: requirements themselves rather than names that would have to be looked up
#: again — looking them up again in the global registry silently drops the
#: requirements of any strategy passed in explicitly, which is exactly the bug
#: this shape prevents.
Requirements = Tuple[Tuple[str, Optional[Tuple[int, int]], Optional[frozenset]], ...]


def _requirements(available: Mapping[str, type]) -> Requirements:
    return tuple(sorted(
        (name, _minimum_capability(name, cls), _supported_dtypes(name, cls))
        for name, cls in available.items()
    ))


def _is_allowed(
    name: str,
    capability: Tuple[int, int],
    requirements: Requirements,
    dtype: Optional[str] = None,
) -> bool:
    """Registered here, supported by this card, and correct in this dtype."""
    for candidate, required, dtypes in requirements:
        if candidate != name:
            continue
        if required is not None and capability < required:
            return False
        if dtype is not None and dtypes is not None and dtype not in dtypes:
            return False
        return True
    return False


def _registry() -> Dict[str, type]:
    from src.strategies import STRATEGIES

    return dict(STRATEGIES)


# ---------------------------------------------------------------------------
# nearest neighbour
# ---------------------------------------------------------------------------

def _parse_key(raw: str) -> Optional[DispatchKey]:
    parts = raw.split(",")
    if len(parts) != 7:
        return None
    try:
        return DispatchKey(
            batch=int(parts[0]), seq_len=int(parts[1]), d_model=int(parts[2]),
            heads=int(parts[3]), dtype=parts[4],
            causal=parts[5].strip().lower() == "true",
            padded=parts[6].strip().lower() == "true",
        )
    except ValueError:
        return None


def _nearest(key: DispatchKey, entries: Mapping[str, str]) -> Optional[Tuple[str, str]]:
    """Closest measured key sharing (dtype, causal, padded).

    Distance is log-scaled on sequence length and batch, because these axes are
    swept multiplicatively: S=1024 is far closer to S=2048 than the linear gap
    to S=128 suggests, and a linear metric would pick the wrong neighbour every
    time.

    Only keys with the *same* mask and dtype behaviour are considered. Borrowing
    a measurement across a causal/padded boundary would mean recommending a
    kernel for a branch it was never measured on.
    """
    candidates = []
    for raw, strategy in entries.items():
        parsed = _parse_key(raw)
        if parsed is None:
            continue
        if (parsed.dtype, parsed.causal, parsed.padded) != (key.dtype, key.causal, key.padded):
            continue
        distance = (
            abs(math.log2(max(parsed.seq_len, 1) / max(key.seq_len, 1))),
            abs(math.log2(max(parsed.batch, 1) / max(key.batch, 1))),
            abs(math.log2(max(parsed.d_model, 1) / max(key.d_model, 1))),
        )
        candidates.append((distance, raw, strategy))
    if not candidates:
        return None
    _, raw, strategy = min(candidates, key=lambda item: item[0])
    return raw, strategy


