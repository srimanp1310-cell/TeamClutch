"""Shape and capability -> strategy selection.

The problem statement invites this directly: "participants can choose different
implementations for different shapes by adding shape checks in the
implementation of layers". This module is that choice, made from measurements
rather than from intuition.

The table it reads is generated by `analysis/load.py` from `results.csv`, so a
dispatch decision is traceable to the rows that justify it. But the submission
must never *depend* on a generated artefact — a judge cloning the repo and
running it with no `results/` directory has to get a working model, not a
crash — so a conservative table is hard-coded here as the fallback.

Selection order
---------------
1. No CUDA at all -> the CPU fallback strategy.
2. Exact match on this GPU's capability block.
3. Nearest measured neighbour: same (dtype, causal, padded), then closest
   sequence length in log space, then closest batch.
4. The table's overall default.
5. `"baseline"`, which is always registered and always correct.

Every step is filtered by three gates that can only remove candidates, never add
them. The strategy must be **registered** on this machine, **supported by this
GPU's capability**, and **numerically correct in the requested dtype**.

The third gate is the subtle one. A strategy can be perfectly implemented, fast,
and still unable to meet the tolerance in a given precision — bf16 against this
reference is the worked example (see `docs/INTERFACE.md` §5.1). Such a strategy
declares `SUPPORTED_DTYPES`, and dispatch will never hand it an input it cannot
compute correctly. Without this gate the hard-coded fallback would happily
select a fp32/fp16-only strategy for a bf16 tensor and return quietly wrong
numbers, which is the worst failure mode available: not a crash, not a slowdown,
but a plausible wrong answer.

Cost
----
`select_strategy` is memoised on its arguments, so the steady-state cost in a
forward pass is a dict lookup on a small tuple. Building the key is the only
part that touches the tensor; see `DispatchKey.from_forward` for the one
GPU-sync hazard there and how to avoid it.
"""

from __future__ import annotations

import functools
import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Mapping, Optional, Sequence, Tuple

import torch

__all__ = [
    "DispatchKey", "Decision", "device_capability", "capability_name",
    "select_strategy", "explain", "load_table", "clear_caches",
    "CPU_FALLBACK_STRATEGY", "FALLBACK_TABLE",
]

DEFAULT_TABLE_PATH = "results/dispatch_table.json"

#: What to run when there is no GPU at all.
#:
#: `"baseline"` is the safe answer and the current one. Whether an SDPA path is
#: numerically safe on CPU is an open question for Person A
#: (docs/APPROVALS_NEEDED.md 1.2); until it is answered, a wrong answer here
#: would fail the correctness oracle on the only machine that runs it in CI.
CPU_FALLBACK_STRATEGY = "baseline"

#: Used when `results/dispatch_table.json` is absent. Deliberately tiny: it
#: encodes the *mechanism* rather than any measurement. Attention is the term
#: that grows as S^2, so a path that avoids materializing [B, H, S, S] should
#: win at long sequences; that is a prediction, not a result, and it is replaced
#: by measured data the moment a sweep has run. Everything in it still passes
#: through the registration and capability gates.
FALLBACK_TABLE: Dict[str, object] = {
    "default": "sdpa",
    "meta": {"source": "hard-coded fallback in src/dispatch.py — not measured"},
}

#: Minimum compute capability per strategy, when the strategy class does not
#: declare `MIN_CAPABILITY` itself. Name-based, because dispatch has to work
#: from the JSON table alone, before any class is imported.
#:
#: (8, 0) — bf16 arithmetic needs Ampere; on Turing it is emulated and slow.
#: (7, 5) — Triton and flash-style kernels need Turing or newer.
_NAME_CAPABILITY_RULES: Sequence[Tuple[str, Tuple[int, int]]] = (
    ("bf16", (8, 0)),
    ("bfloat16", (8, 0)),
    ("triton", (7, 5)),
    ("flash", (7, 5)),
)


@dataclass(frozen=True)
class DispatchKey:
    """Everything the dispatcher is allowed to see at call time.

    Note what is absent: `layers`. Depth changes how long a forward pass takes
    but not which kernel is right for a shape, and including it would fragment
    the table into keys that were never measured separately.
    """

    batch: int
    seq_len: int
    d_model: int
    heads: int
    dtype: str
    causal: bool
    padded: bool

    def table_key(self) -> str:
        """The exact string `analysis/load.py` writes as a JSON key."""
        return ",".join((
            str(self.batch), str(self.seq_len), str(self.d_model),
            str(self.heads), str(self.dtype), str(self.causal), str(self.padded),
        ))

    @classmethod
    def from_forward(
        cls,
        x: torch.Tensor,
        valid_token_mask: Optional[torch.Tensor],
        config,
        padded: Optional[bool] = None,
    ) -> "DispatchKey":
        """Build a key inside `forward`.

        `padded` is worth passing explicitly. Deriving it means asking whether
        the mask is all-True, and on CUDA that reduction has to be read back to
        the host — a synchronisation in the middle of a hot forward pass. It is
        cheap relative to a long-sequence forward and not cheap relative to a
        short one. In the benchmark harness padding is a property of the
        configuration and is known before the call, so pass it and skip the
        question entirely.
        """
        batch, seq_len, d_model = x.shape
        if padded is None:
            padded = bool(
                valid_token_mask is not None and not bool(valid_token_mask.all())
            )
        return cls(
            batch=int(batch), seq_len=int(seq_len), d_model=int(d_model),
            heads=int(config.num_heads), dtype=str(x.dtype).replace("torch.", ""),
            causal=bool(config.causal), padded=bool(padded),
        )


@dataclass(frozen=True)
class Decision:
    """A chosen strategy plus why, so a run can always explain itself."""

    strategy: str
    reason: str


def device_capability(device: Optional[torch.device] = None) -> Optional[Tuple[int, int]]:
    """(major, minor) for the current CUDA device, or None when there is no GPU."""
    if not torch.cuda.is_available():
        return None
    try:
        return tuple(torch.cuda.get_device_capability(device))  # type: ignore[return-value]
    except (RuntimeError, AssertionError):
        return None


def capability_name(capability: Tuple[int, int]) -> str:
    """(8, 9) -> 'sm_89'. The key `analysis/load.py` writes its block under."""
    return f"sm_{capability[0]}{capability[1]}"


@functools.lru_cache(maxsize=8)
def load_table(table_path: str = DEFAULT_TABLE_PATH) -> Mapping[str, object]:
    """Read the generated table, or fall back. Cached; never raises.

    A malformed or missing file degrades to `FALLBACK_TABLE` rather than
    propagating: this runs inside `forward`, and a model that refuses to run
    because a JSON file is unreadable is worse than one that runs a slower
    kernel.
    """
    path = Path(table_path)
    try:
        table = json.loads(path.read_text())
    except (OSError, ValueError):
        return FALLBACK_TABLE
    if not isinstance(table, dict):
        return FALLBACK_TABLE
    return table


def clear_caches() -> None:
    """Drop memoised tables and decisions. For tests, and after a re-sweep."""
    load_table.cache_clear()
    _select_cached.cache_clear()


