# selection
# ---------------------------------------------------------------------------

_AUTO = object()


def _decide(
    key: DispatchKey,
    capability: Optional[Tuple[int, int]],
    table_path: str,
    requirements: Requirements,
) -> Decision:
    if capability is None:
        return Decision(
            CPU_FALLBACK_STRATEGY,
            f"no CUDA device -> {CPU_FALLBACK_STRATEGY}",
        )

    table = load_table(table_path)
    block_name = capability_name(capability)
    raw_block = table.get(block_name)
    measured_here = isinstance(raw_block, dict) and bool(raw_block)
    entries = raw_block if isinstance(raw_block, dict) else {}

    def gated(name: Optional[str]) -> bool:
        return bool(name) and _is_allowed(
            str(name), capability, requirements, key.dtype
        )

    # 3. exact match
    exact = entries.get(key.table_key())
    if gated(exact):
        return Decision(str(exact), f"exact match {block_name} {key.table_key()} -> {exact}")
    rejected = f" (measured {exact!r} rejected: {_why_rejected(str(exact), capability, requirements, key.dtype)})" if exact else ""

    # 4. nearest measured neighbour
    neighbour = _nearest(key, {k: v for k, v in entries.items() if gated(v)})
    if neighbour is not None:
        raw, strategy = neighbour
        return Decision(
            strategy,
            f"nearest measured neighbour {block_name} {raw} -> {strategy}{rejected}",
        )

    # 5. the table's default
    default = table.get("default")
    if gated(default):
        # Distinguish "we measured this card but not this shape" from "we have
        # never measured this card at all". The report has to be able to say
        # which, because only the first is a performance claim.
        if table is FALLBACK_TABLE:
            why = "no measured data at all; hard-coded fallback default"
        elif measured_here:
            why = f"no {block_name} key for {key.table_key()}; table default"
        else:
            why = f"no measured data for {block_name}; table default"
        return Decision(str(default), f"{why} -> {default}{rejected}")

    # 6. the control, which is always registered and always correct
    return Decision(
        "baseline",
        f"nothing applicable for {block_name} {key.table_key()} -> baseline{rejected}",
    )


def _why_rejected(
    name: str, capability: Tuple[int, int], requirements: Requirements, dtype: str
) -> str:
    """Which gate removed this candidate. "Rejected" alone is not actionable."""
    for candidate, required, dtypes in requirements:
        if candidate != name:
            continue
        if required is not None and capability < required:
            return f"needs sm_{required[0]}{required[1]}+, this card is {capability_name(capability)}"
        if dtypes is not None and dtype not in dtypes:
            return f"does not support {dtype} (declares {sorted(dtypes)})"
        return "allowed"
    return "not registered on this machine"


@functools.lru_cache(maxsize=512)
def _select_cached(
    key: DispatchKey,
    capability: Optional[Tuple[int, int]],
    table_path: str,
    requirements: Requirements,
) -> Decision:
    return _decide(key, capability, table_path, requirements)


def _decide_for(
    key: DispatchKey,
    capability,
    table_path: str,
    available: Optional[Mapping[str, type]],
) -> Decision:
    if capability is _AUTO:
        capability = device_capability()
    if available is None:
        available = _registry()
    return _select_cached(key, capability, table_path, _requirements(available))


def select_strategy(
    key: DispatchKey,
    capability=_AUTO,
    table_path: str = DEFAULT_TABLE_PATH,
    available: Optional[Mapping[str, type]] = None,
) -> str:
    """The strategy name to use for `key`.

    `capability` defaults to auto-detection. Pass an explicit `(major, minor)`
    to force a decision for another card — that is how the sm_75 and sm_80 paths
    are correctness-tested without owning those cards — or an explicit `None` to
    force the no-GPU path.

    `available` defaults to the live strategy registry; pass a mapping to test
    selection independently of what happens to be registered.

    **This function is depth-blind.** `DispatchKey` carries no layer count, and
    numerical admissibility can depend on one: fp16 passes at a single layer and
    fails from two, once error has compounded through the residual stream. A
    strategy declaring `SUPPORTED_DTYPES = (float32, float16)` is telling the
    truth, and this function will still offer it an fp16 tensor at six layers
    where it fails. Any such depth rule belongs in the entry point that knows
    the config -- `src/optimized.py` -- not here. See TECH_REPORT §7.2.
    """
    return _decide_for(key, capability, table_path, available).strategy


def explain(
    key: DispatchKey,
    capability=_AUTO,
    table_path: str = DEFAULT_TABLE_PATH,
    available: Optional[Mapping[str, type]] = None,
) -> str:
    """One line saying which strategy was chosen and why.

    Worth logging at least once per process: a speedup nobody can attribute to a
    specific code path is not a result anyone can act on.
    """
    return _decide_for(key, capability, table_path, available).reason
